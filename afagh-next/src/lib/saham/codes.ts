/**
 * یکسان‌سازی نویسه‌های فارسی/عربی برای مقایسه:
 * ی(U+06CC) و ى(U+0649) → ي(U+064A)، ک(U+06A9) → ك(U+0643)،
 * حذف نیم‌فاصله و یکسان‌سازی فاصله‌ها.
 *
 * لازم است چون فهرست‌های رسمی سهام بیشتر با «ي/ك» عربی نوشته شده‌اند و
 * دادهٔ ما با «ی/ک» فارسی — بدون این کار، «کارشناسی ارشد» با
 * «كارشناسي ارشد» مطابقت نمی‌کرد و ستون‌ها بی‌دلیل خالی می‌شدند.
 */
function normFa(s: string): string {
  return s
    .replace(/[\u06CC\u0649]/g, '\u064A')
    .replace(/\u06A9/g, '\u0643')
    .replace(/\u200C/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** نگاشت نرمال‌شدهٔ هر فهرست (تنبل) → املاي رسمی سهام */
const NORM_CACHE = new Map<string, Map<string, string>>();

function normList(field: string): Map<string, string> {
  let m = NORM_CACHE.get(field);
  if (!m) {
    m = new Map();
    for (const v of SAHAM_CLOSED_LISTS[field] ?? []) m.set(normFa(v), v);
    NORM_CACHE.set(field, m);
  }
  return m;
}

/**
 * نگاشت «امنِ» ستون‌های فهرست‌بسته: خروجی همیشه یا متن رسمی سهام است یا ''.
 *
 *   ۱) نگاشت داخلیِ `saham_value_maps` (منبع حقیقت، قابل ویرایش)
 *   ۲) اگر خودِ مقدار با یکی از مقادیر فهرست یکی باشد (حتی با املای
 *      متفاوت ی/ک) → **املای رسمی سهام** برگردانده می‌شود
 *   ۳) وگرنه '' — هرگز متن انگلیسی/کد داخلی به سهام نمی‌رود
 */
export function mapSahamClosed(
  maps: Record<string, Record<string, string>>,
  field: string,
  value: unknown,
): string {
  if (value == null) return '';
  const v = String(value).trim();
  if (!v) return '';
  const mapped = maps[field]?.[v] ?? maps[field]?.[normFa(v)];
  if (mapped) return mapped;
  const list = SAHAM_CLOSED_LISTS[field];
  if (list) {
    const exact = list.includes(v);
    if (exact) return v;
    const near = normList(field).get(normFa(v));
    if (near) return near;
    return '';
  }
  // فیلدهای کدینگ بدون فهرست (مثل student_status_code) → فقط از نگاشت داخلی
  return '';
}
