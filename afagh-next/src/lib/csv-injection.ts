/**
 * گارد تزریق فرمول CSV (OWASP CSV Injection) — تک‌منبعِ حقیقت.
 *
 * چرا این فایل جدا شد: پیش‌تر همین دو تابع عیناً در `export-utils.ts` (سمت
 * کلاینت) و `export-doc.ts` (سمت سرور) تکرار شده بودند. تکرارِ یک گارد امنیتی
 * ریسک است: کافی است یک نسخه اصلاح و دیگری فراموش شود تا مسیرِ خروجیِ دوم
 * آسیب‌پذیر بماند. حالا هر دو ماژول از همین‌جا می‌خوانند.
 *
 * قرارداد: مقداری که (پس از trim چپ) با = + - @ | تب یا CR شروع شود، با یک
 * تک‌کوتیشن پیشوند می‌گیرد تا Excel/LibreOffice آن را فرمول اجرا نکند؛ سپس
 * نقل‌قول دوتایی برای CSV escape می‌شود.
 *
 * ⚠️ این ماژول هیچ وابستگی‌ای ندارد (نه server-only، نه کلاینت) تا هم در
 * route handler و هم در کامپوننت کلاینت قابل استفاده باشد.
 */

/** پیشوند خنثی‌سازی فرمول؛ اگر لازم نبود رشته را دست‌نخورده برمی‌گرداند. */
export function csvFormulaPrefix(s: string): string {
  return /^[=+\-@|\t\r]/.test(s.trimStart()) ? `'${s}` : s;
}

/** یک سلول CSV: گارد فرمول + نقل‌قول دوتایی (بدون قالب‌بندی مقدار). */
export function csvQuote(v: unknown): string {
  return `"${csvFormulaPrefix(String(v ?? '')).replace(/"/g, '""')}"`;
}
