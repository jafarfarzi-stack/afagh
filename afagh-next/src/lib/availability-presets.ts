/**
 * «روزهای زوج/فرد» بر پایهٔ شمارهٔ روز در تقویم ایرانی، نه ایندکس ۰‑پایهٔ ستون جدول.
 *
 * شنبه روزِ ۱ هفته است؛ پس روزهای فرد = شنبه(۰)، دوشنبه(۲)، چهارشنبه(۴)، جمعه(۶)
 * و روزهای زوج = یکشنبه(۱)، سه‌شنبه(۳)، پنج‌شنبه(۵).
 *
 * پیاده‌سازی قبلی `d % 2 === 1` را «فرد» می‌گرفت که دقیقاً برعکسِ عرف تقویم
 * ایرانی است: استاد با یک کلیک روی «روزهای فرد»، یکشنبه/سه‌شنبه/پنج‌شنبه را
 * اولویت‌دار می‌کرد و شنبه/دوشنبه/چهارشنبه را «عدم حضور» — بی‌آنکه متوجه شود.
 * (در تست زندهٔ ۵ ایجنتی روی نسخهٔ مستقر کشف شد.)
 */
export const isOddWeekday = (dayIndex: number): boolean => dayIndex % 2 === 0;
export const isEvenWeekday = (dayIndex: number): boolean => dayIndex % 2 === 1;
