/**
 * محتوای راهنمای نقش‌محور سامانه آفاق (/help)
 * هر تب = یک نقش؛ همین داده هم برای صفحه وب و هم برای نسخه چاپی/PDF استفاده می‌شود.
 */

export type HelpLink = { href: string; label: string; desc?: string };

export type HelpSection = {
  id: string;
  icon: string;
  title: string;
  intro?: string;
  steps?: string[];
  links?: HelpLink[];
  note?: string;
};

export type TabKey = 'student' | 'professor' | 'group-manager' | 'admin' | 'shared';

export type HelpTab = {
  key: TabKey;
  label: string;
  icon: string;
  color: string;
  subtitle: string;
  pdf: string;
  sections: HelpSection[];
};

export const TAB_KEYS: TabKey[] = ['student', 'professor', 'group-manager', 'admin', 'shared'];

export function isTabKey(v: unknown): v is TabKey {
  return typeof v === 'string' && (TAB_KEYS as string[]).includes(v);
}

/** تشخیص تب پیش‌فرض از روی نقش‌های نشست کاربر */
export function defaultTabForRoles(roles: string[]): TabKey {
  if (roles.includes('ADMIN')) return 'admin';
  if (roles.includes('DEP_HEAD')) return 'group-manager';
  if (roles.includes('PROFESSOR')) return 'professor';
  if (roles.includes('STUDENT')) return 'student';
  return 'shared';
}

