#!/usr/bin/env node
/**
 * تولید نگاشت staffCode → nationalCode از فایل‌های مبدأ (فقط خواندنی، برای لاگین).
 * این نگاشت فقط «مجموعهٔ کاندیداها» را در لاگین گسترش می‌دهد؛ ورود به هر حساب
 * همچنان رمزِ همان حساب را می‌خواهد. پس نگاشتِ اشتباه نمی‌تواند دسترسی بدهد.
 *
 *   node scripts/generate-staff-nc-map.mjs   # writes src/lib/staff-nc-map.generated.ts
 */
import { createReadStream } from 'node:fs';
import { writeFileSync } from 'node:fs';

const FILES = [
  { path: '/root/information-afagh/ostadan.txt', ncIdx: [31, 32], nameCol: 1 },
  { path: '/root/information-afagh/اساتید2.txt', ncIdx: [26, 27], nameCol: 0 },
];
const dec = new TextDecoder('windows-1256');
async function* fileRows(path) {
  const st = createReadStream(path, { highWaterMark: 8 * 1024 * 1024 });
  let carry = Buffer.alloc(0);
  let header = 0;
  for await (const chunk of st) {
    const buf = Buffer.concat([carry, chunk]);
    let start = 0;
    for (let i = 0; i < buf.length; i++) {
      if (buf[i] !== 10) continue;
      const line = dec.decode(buf.subarray(start, i)).replace(/\r/g, '');
      start = i + 1;
      if (!line.trim()) continue;
      const cols = line.split('\t');
      if (!header) {
        header = 1;
        continue;
      }
      yield cols;
    }
    carry = buf.subarray(start);
  }
}
const isPlausibleNC = (v) =>
  /^\d{10}$/.test(v) && !/^(\d)\1{9}$/.test(v) && !['1234567890', '9876543210', '0123456789'].includes(v);

const map = new Map();
for (const f of FILES) {
  for await (const cols of fileRows(f.path)) {
    const code = String(cols[0] ?? '').trim();
    if (!/^\d+$/.test(code) || code === '0') continue;
    if (map.has(code)) continue; // ostadan ملاک است، اساتید2 fallback
    for (const i of f.ncIdx) {
      const v = String(cols[i] ?? '').trim();
      if (v !== code && isPlausibleNC(v)) {
        map.set(code, v);
        break;
      }
    }
  }
}
const entries = [...map].sort((a, b) => a[0].localeCompare(b[0], 'en', { numeric: true }));
const out = `// ⚠️ AUTO-GENERATED by scripts/generate-staff-nc-map.mjs — دستی ویرایش نکنید.
// نگاشت کد استاد → کد ملی از فایل‌های مبدأ. فقط روی سرور استفاده می‌شود.
import 'server-only';

export const STAFF_NC_MAP: Record<string, string> = ${JSON.stringify(Object.fromEntries(entries))};
`;
writeFileSync(new URL('../src/lib/staff-nc-map.generated.ts', import.meta.url), out);
console.log(`negasht: ${map.size} کد استاد → src/lib/staff-nc-map.generated.ts`);
