-- ────────────────────────────────────────────────────────────────────────
--  «الزامی در ترم» ⇒ «شرط فارغ‌التحصیلی»
--
--  دو پرچم جدا بودند و می‌شد درسی الزامی باشد ولی «شرط فارغ‌التحصیلی» نه؛
--  نتیجه: اعتبارسنجی چارت با خطای GRADUATION_COVERAGE می‌افتاد در حالی که
--  دروس الزامی وجود داشت.
--
--  قاعده (یک‌طرفه): هر درسِ الزامی، شرط فارغ‌التحصیلی هم هست. عکسش لازم نیست:
--  پایان‌نامه/کارآموزی می‌توانند شرط فارغ‌التحصیلی باشند بدون «الزامیِ ترم».
-- ────────────────────────────────────────────────────────────────────────
UPDATE "curriculum_courses"
SET "isGraduationRequired" = 1
WHERE "isRequired" = 1
  AND coalesce("isGraduationRequired", 0) = 0;
