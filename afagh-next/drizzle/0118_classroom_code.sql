-- «کد کلاس» — همراهِ نام، کلاس را برای تفکیکِ کلاس‌های هم‌نام (درخواست کاربر) مشخص می‌کند.
--
-- تاکنون کلاس فقط با نام تعریف می‌شد که باعث ابهام می‌شد (مثلاً چند «كلاس 1»
-- در ساختمان‌های مختلف، یا «سايت 1»های گوناگون). حالا مدیرگروه می‌تواند کد
-- اختصاصی (مثل C-101، LAB2، SITE-A) بدهد و در لیست/برنامه آن را ببیند.
--
-- ستون nullable است تا کلاس‌های قبلی بدون کد بمانند و مهاجرت بی‌خطر باشد.
-- یکتایی فقط داخل هر دانشگاه (universityId) اعمال می‌شود — دانشگاه‌های مختلف
-- می‌توانند کدهای یکسان داشته باشند؛ کدِ خالی (NULL) هم شامل یکتایی نمی‌شود تا
-- چند کلاسِ بی‌کد مجاز باشند (هم‌راستا با مهاجرت ۰۰۲۴ — یکتاییِ محدود به دانشگاه).

ALTER TABLE "classrooms" ADD COLUMN IF NOT EXISTS "code" varchar(30);

CREATE UNIQUE INDEX IF NOT EXISTS "idx_classrooms_uni_code"
  ON "classrooms" ("universityId", "code") WHERE "code" IS NOT NULL;
