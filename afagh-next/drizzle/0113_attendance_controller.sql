-- نقشِ «کنترل‌کنندهٔ حضور و غیاب کلاس‌ها»
--
-- چرا: استاد همیشه سرِ کلاس نیست که QRِ سردر را اسکن کند — گوشی ندارد، در
-- آزمایشگاه است، یا کلاسِ هم‌زمان دارد. کنترل‌کننده کسی است که فقط و فقط یک
-- کار می‌کند: سرِ ساعت سرِ کلاس می‌رسد و «تشکیل کلاس» را ثبت می‌کند. این نقش
-- هیچ دسترسیِ آموزشی/مالیِ دیگری ندارد تا اصلِ کمترین سطحِ دسترسی رعایت شود.
--
-- دامنهٔ اتاق‌ها: همان جدولِ `classroom_edu_experts` (مهاجرت ۰۱۱۲). مدیر از
-- صفحهٔ «تخصیص کارشناس به اتاق‌ها» کنترل‌کننده را به اتاق‌ها می‌بندد. اگر
-- تنظیمِ `ATTENDANCE_CONTROLLER_ROOM_SCOPED` خاموش شود، دامنه به کلِ دانشگاه
-- گسترش می‌یابد (برای دانشگاه‌های کوچک که یک نفر همهٔ اتاق‌ها را می‌گردد).
--
-- ⚠ هیچ GRANT/POLICY تازه‌ای لازم نیست: نه جدولِ تازه‌ای ساخته می‌شود و نه
--   ستونِ تازه‌ای. جدولِ `roles` از پیش در سخت‌سازیِ امنیتی
--   (`scripts/hardening.mjs`) پوشش دارد. ثبتِ حضور هم از همان جدولِ موجودِ
--   `professor_class_attendance` استفاده می‌کند و «چه کسی ثبت کرد» را در
--   ستونِ موجودِ `confirmedByStaffId` نگه می‌دارد — بدون تغییرِ ساختار.

INSERT INTO "roles" ("code", "title", "isSystem")
SELECT 'ATTENDANCE_CONTROLLER', 'کنترل‌کنندهٔ حضور و غیاب کلاس‌ها', 0
WHERE NOT EXISTS (SELECT 1 FROM "roles" WHERE "code" = 'ATTENDANCE_CONTROLLER');
